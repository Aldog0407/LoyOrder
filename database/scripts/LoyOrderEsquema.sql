-- LOYORDER | Actividad 7.1.2 | PostgreSQL
-- Base: Actividad 3.3, modelo y diccionario de datos (Equipo 05).
-- 22 tablas, PK/FK, restricciones e indices. Ejecutar sobre una BD nueva.
-- No contiene tokens, correos ni contrasenas reales.
BEGIN;

-- 1. Operacion del restaurante (tablas padre)
CREATE TABLE restaurante (
    id_restaurante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    id_tienda_loyverse VARCHAR(100) UNIQUE,
    token_loyverse_cifrado TEXT,
    horario_apertura TIME NOT NULL,
    horario_cierre TIME NOT NULL,
    costo_envio NUMERIC(12,2) NOT NULL CHECK (costo_envio >= 0),
    intervalo_sincronizacion INTEGER NOT NULL DEFAULT 2 CHECK (intervalo_sincronizacion BETWEEN 1 AND 15)
);

CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    correo VARCHAR(150) NOT NULL UNIQUE,
    contrasena_hash VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cliente (
    id_cliente BIGINT PRIMARY KEY REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    telefono VARCHAR(20)
);

CREATE TABLE empleado (
    id_empleado BIGINT PRIMARY KEY REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_restaurante BIGINT NOT NULL REFERENCES restaurante(id_restaurante),
    numero_empleado VARCHAR(30) UNIQUE,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('ADMINISTRADOR', 'OPERADOR'))
);

CREATE TABLE direccion (
    id_direccion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES cliente(id_cliente) ON DELETE CASCADE,
    calle VARCHAR(150) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    colonia VARCHAR(100),
    codigo_postal VARCHAR(10),
    referencias TEXT,
    latitud NUMERIC(10,7) CHECK (latitud BETWEEN -90 AND 90),
    longitud NUMERIC(10,7) CHECK (longitud BETWEEN -180 AND 180)
);

-- 2. Catalogo: los datos oficiales se sincronizan desde Loyverse
CREATE TABLE categoria (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_restaurante BIGINT NOT NULL REFERENCES restaurante(id_restaurante),
    id_loyverse VARCHAR(100) UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE producto (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria BIGINT NOT NULL REFERENCES categoria(id_categoria),
    id_loyverse VARCHAR(100) UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    imagen_url TEXT,
    disponible BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE variante_producto (
    id_variante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL REFERENCES producto(id_producto),
    id_loyverse VARCHAR(100) UNIQUE,
    nombre VARCHAR(100),
    precio NUMERIC(12,2) NOT NULL CHECK (precio >= 0),
    existencias NUMERIC(12,3),
    controla_inventario BOOLEAN NOT NULL DEFAULT FALSE,
    disponible BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE metodo_pago (
    id_metodo_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_restaurante BIGINT NOT NULL REFERENCES restaurante(id_restaurante),
    nombre VARCHAR(50) NOT NULL,
    id_loyverse VARCHAR(100) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- 3. Carrito y pedidos
CREATE TABLE carrito (
    id_carrito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT UNIQUE REFERENCES cliente(id_cliente) ON DELETE CASCADE,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE item_carrito (
    id_item BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carrito BIGINT NOT NULL REFERENCES carrito(id_carrito) ON DELETE CASCADE,
    id_variante BIGINT NOT NULL REFERENCES variante_producto(id_variante),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12,2) NOT NULL CHECK (precio_unitario >= 0)
);

CREATE TABLE pedido (
    id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio VARCHAR(30) UNIQUE NOT NULL,
    id_cliente BIGINT NOT NULL REFERENCES cliente(id_cliente),
    id_direccion BIGINT REFERENCES direccion(id_direccion),
    id_metodo_pago BIGINT NOT NULL REFERENCES metodo_pago(id_metodo_pago),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_entrega TIMESTAMPTZ,
    estado VARCHAR(25) NOT NULL DEFAULT 'Recibido' CHECK (estado IN (
        'Recibido', 'En preparación', 'Enviado', 'Listo para recoger', 'Entregado', 'Cancelado'
    )),
    tipo_entrega VARCHAR(20) NOT NULL CHECK (tipo_entrega IN ('Domicilio', 'Recolección')),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    costo_envio NUMERIC(12,2) NOT NULL CHECK (costo_envio >= 0),
    total NUMERIC(12,2) NOT NULL CHECK (total >= 0),
    calificacion SMALLINT CHECK (calificacion BETWEEN 1 AND 5),
    comentario TEXT,
    CONSTRAINT pedido_total_consistente CHECK (total = subtotal + costo_envio),
    CONSTRAINT pedido_direccion_domicilio CHECK (tipo_entrega <> 'Domicilio' OR id_direccion IS NOT NULL),
    CONSTRAINT pedido_sin_envio_recoleccion CHECK (tipo_entrega <> 'Recolección' OR costo_envio = 0)
);

CREATE TABLE detalle_pedido (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES pedido(id_pedido),
    id_variante BIGINT NOT NULL REFERENCES variante_producto(id_variante),
    nombre_producto VARCHAR(150) NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12,2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    indicaciones TEXT,
    CONSTRAINT detalle_subtotal_consistente CHECK (subtotal = cantidad * precio_unitario)
);

CREATE TABLE historial_estado (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES pedido(id_pedido),
    id_empleado BIGINT REFERENCES empleado(id_empleado),
    estado_anterior VARCHAR(25),
    estado_nuevo VARCHAR(25) NOT NULL CHECK (estado_nuevo IN (
        'Recibido', 'En preparación', 'Enviado', 'Listo para recoger', 'Entregado', 'Cancelado'
    )),
    fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo TEXT
);

CREATE TABLE modificacion_pedido (
    id_modificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES pedido(id_pedido),
    id_empleado BIGINT NOT NULL REFERENCES empleado(id_empleado),
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_cambio VARCHAR(30) NOT NULL,
    descripcion TEXT NOT NULL,
    datos_anteriores JSONB,
    datos_nuevos JSONB
);

-- 4. Estaciones e impresion
CREATE TABLE impresora (
    id_impresora BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_restaurante BIGINT NOT NULL REFERENCES restaurante(id_restaurante),
    nombre VARCHAR(100) NOT NULL,
    direccion_ip VARCHAR(45) NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('Cocina', 'Caja')),
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE estacion_preparacion (
    id_estacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_restaurante BIGINT NOT NULL REFERENCES restaurante(id_restaurante),
    id_impresora BIGINT NOT NULL UNIQUE REFERENCES impresora(id_impresora),
    nombre VARCHAR(100) NOT NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE asignacion_estacion (
    id_asignacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estacion BIGINT NOT NULL REFERENCES estacion_preparacion(id_estacion),
    id_categoria BIGINT REFERENCES categoria(id_categoria),
    id_variante BIGINT REFERENCES variante_producto(id_variante),
    CONSTRAINT asignacion_exactamente_una CHECK (
        (id_categoria IS NOT NULL AND id_variante IS NULL) OR
        (id_categoria IS NULL AND id_variante IS NOT NULL)
    )
);

CREATE TABLE comanda (
    id_comanda BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES pedido(id_pedido),
    id_estacion BIGINT REFERENCES estacion_preparacion(id_estacion),
    id_impresora BIGINT NOT NULL REFERENCES impresora(id_impresora),
    tipo_comanda VARCHAR(25) NOT NULL CHECK (tipo_comanda IN ('Normal', 'Adicional', 'Anulación', 'Prioritario')),
    contenido JSONB NOT NULL,
    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado_impresion VARCHAR(20) NOT NULL DEFAULT 'Pendiente' CHECK (estado_impresion IN ('Pendiente', 'Enviada', 'Fallida')),
    intentos INTEGER NOT NULL DEFAULT 0 CHECK (intentos >= 0)
);

-- 5. Integracion con Loyverse y notificaciones
CREATE TABLE registro_venta (
    id_registro BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL UNIQUE REFERENCES pedido(id_pedido),
    id_recibo_loyverse VARCHAR(100) UNIQUE,
    numero_recibo VARCHAR(50),
    estado_sincronizacion VARCHAR(20) NOT NULL DEFAULT 'Pendiente' CHECK (estado_sincronizacion IN (
        'Pendiente', 'En proceso', 'Confirmado', 'Fallido', 'Por verificar'
    )),
    fecha_registro TIMESTAMPTZ,
    intentos INTEGER NOT NULL DEFAULT 0 CHECK (intentos >= 0),
    ultimo_error TEXT
);

CREATE TABLE sincronizacion (
    id_sincronizacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_restaurante BIGINT NOT NULL REFERENCES restaurante(id_restaurante),
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('Catálogo', 'Inventario')),
    fecha_inicio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_fin TIMESTAMPTZ,
    estado VARCHAR(20) NOT NULL,
    detalle_error TEXT
);

CREATE TABLE notificacion (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT REFERENCES pedido(id_pedido),
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    asunto VARCHAR(150) NOT NULL,
    mensaje TEXT NOT NULL,
    fecha_envio TIMESTAMPTZ,
    estado_envio VARCHAR(20) NOT NULL DEFAULT 'Pendiente' CHECK (estado_envio IN ('Pendiente', 'Enviada', 'Fallida'))
);

-- 6. Indices para claves foraneas, listados por estado y consultas frecuentes
CREATE INDEX idx_empleado_restaurante ON empleado (id_restaurante);
CREATE INDEX idx_direccion_cliente ON direccion (id_cliente);
CREATE INDEX idx_categoria_restaurante ON categoria (id_restaurante);
CREATE INDEX idx_producto_categoria ON producto (id_categoria);
CREATE INDEX idx_variante_producto ON variante_producto (id_producto);
CREATE INDEX idx_metodo_pago_restaurante ON metodo_pago (id_restaurante);
CREATE INDEX idx_item_carrito_carrito ON item_carrito (id_carrito);
CREATE INDEX idx_item_carrito_variante ON item_carrito (id_variante);
CREATE INDEX idx_pedido_cliente_fecha ON pedido (id_cliente, fecha_creacion DESC);
CREATE INDEX idx_pedido_estado_fecha ON pedido (estado, fecha_creacion DESC);
CREATE INDEX idx_pedido_metodo_pago ON pedido (id_metodo_pago);
CREATE INDEX idx_pedido_direccion ON pedido (id_direccion);
CREATE INDEX idx_detalle_pedido_pedido ON detalle_pedido (id_pedido);
CREATE INDEX idx_detalle_pedido_variante ON detalle_pedido (id_variante);
CREATE INDEX idx_historial_pedido_fecha ON historial_estado (id_pedido, fecha_cambio DESC);
CREATE INDEX idx_historial_empleado ON historial_estado (id_empleado);
CREATE INDEX idx_modificacion_pedido_fecha ON modificacion_pedido (id_pedido, fecha DESC);
CREATE INDEX idx_modificacion_empleado ON modificacion_pedido (id_empleado);
CREATE INDEX idx_impresora_restaurante ON impresora (id_restaurante);
CREATE INDEX idx_estacion_restaurante ON estacion_preparacion (id_restaurante);
CREATE INDEX idx_asignacion_estacion ON asignacion_estacion (id_estacion);
CREATE UNIQUE INDEX uq_asignacion_categoria ON asignacion_estacion (id_categoria) WHERE id_categoria IS NOT NULL;
CREATE UNIQUE INDEX uq_asignacion_variante ON asignacion_estacion (id_variante) WHERE id_variante IS NOT NULL;
CREATE INDEX idx_comanda_pedido ON comanda (id_pedido);
CREATE INDEX idx_comanda_estacion ON comanda (id_estacion);
CREATE INDEX idx_comanda_impresora_estado ON comanda (id_impresora, estado_impresion);
CREATE INDEX idx_registro_venta_estado ON registro_venta (estado_sincronizacion);
CREATE INDEX idx_sincronizacion_restaurante_fecha ON sincronizacion (id_restaurante, fecha_inicio DESC);
CREATE INDEX idx_notificacion_usuario_estado ON notificacion (id_usuario, estado_envio);
CREATE INDEX idx_notificacion_pedido ON notificacion (id_pedido);

COMMIT;
